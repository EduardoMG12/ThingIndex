func T(lang string, key string) string {
	lang = strings.ToLower(lang)
	if !strings.HasPrefix(lang, "pt") && !strings.HasPrefix(lang, "en") {
		lang = "en"
	} else if strings.HasPrefix(lang, "pt") {
		lang = "pt"
	} else {
		lang = "en"
	}

	if msg, ok := Messages[lang][key]; ok {
		return msg
	}
	return key
}
