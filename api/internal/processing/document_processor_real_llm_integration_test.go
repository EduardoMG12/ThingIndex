//go:build integration

package processing

import (
	"bytes"
	"context"
	"strconv"
	"strings"
	"testing"
	"time"

	"thing-index/internal/config"
	"thing-index/internal/domain"
	"thing-index/internal/indexing"
	"thing-index/internal/models"
	"thing-index/internal/repository"
	"thing-index/internal/testutil"
	"thing-index/internal/usecase"
)

func TestDocumentProcessorWithRealLLMEnrichesAndPersistsIndex(t *testing.T) {
	llmCfg := testutil.RequireRealLLMProcessing(t)

	db := testutil.OpenIsolatedPostgresDB(t)
	baseStorage, _ := testutil.NewIntegrationMinioStorage(t)

	user := models.User{
		Name:     "Real LLM",
		Email:    "real-llm-processing@example.com",
		Password: "not-used-in-this-test",
	}
	if err := db.Create(&user).Error; err != nil {
		t.Fatalf("create user: %v", err)
	}

	category := models.DocumentCategory{
		UserID:         user.ID,
		Name:           "Contratos",
		NormalizedName: "contratos",
	}
	if err := db.Create(&category).Error; err != nil {
		t.Fatalf("create category: %v", err)
	}

	collection := models.Collection{
		UserID:         user.ID,
		CategoryID:     &category.ID,
		Name:           "Operacional",
		NormalizedName: "operacional",
	}
	if err := db.Create(&collection).Error; err != nil {
		t.Fatalf("create collection: %v", err)
	}

	htmlBody := []byte(`
<html>
  <body>
    <h1>Contrato de Prestacao de Servicos</h1>
    <p>Este documento descreve a prestacao de servicos de manutencao predial para a unidade de Palmas.</p>
    <h2>Escopo</h2>
    <p>A contratada executara manutencao preventiva mensal e manutencao corretiva sob demanda.</p>
    <h2>Prazos</h2>
    <p>O atendimento emergencial deve ocorrer em ate 4 horas e o relatorio mensal deve ser entregue ate o dia 5.</p>
    <h2>Custos</h2>
    <p>O valor mensal previsto e de R$ 12.000,00 com reajuste anual pelo IPCA.</p>
  </body>
</html>
`)

	fileURL, err := baseStorage.UploadFile(
		context.Background(),
		bytes.NewReader(htmlBody),
		int64(len(htmlBody)),
		"text/html",
		"processing/real-llm-"+strconv.FormatInt(time.Now().UnixNano(), 10)+".html",
	)
	if err != nil {
		t.Fatalf("upload source document to minio: %v", err)
	}

	t.Cleanup(func() {
		_ = baseStorage.DeleteFile(context.Background(), fileURL)
	})

	document := models.Document{
		UserID:          user.ID,
		Title:           "contrato-servicos.html",
		FileURL:         fileURL,
		Size:            int64(len(htmlBody)),
		MimeType:        "text/html",
		Status:          domain.DocumentStatusQueued,
		ProcessingStage: "QUEUED",
		Collection:      collection.Name,
		CollectionID:    &collection.ID,
		CategoryID:      &category.ID,
	}
	if err := db.Create(&document).Error; err != nil {
		t.Fatalf("create document: %v", err)
	}

	providerRepo := repository.NewGormProviderRepository(db)
	providerService := usecase.NewProviderUseCase(providerRepo, &config.Config{
		Environment:                  "development",
		AllowPrivateStorageEndpoints: true,
		MasterEncryptionKey:          "thingindex-real-llm-integration-master-key",
	})

	if err := providerService.SaveCredentials(context.Background(), user.ID, domain.FamilyLLM, llmCfg.ProviderType, llmCfg.Credentials, domain.ProviderActivation{
		EnabledForIndexing: true,
	}); err != nil {
		t.Fatalf("SaveCredentials returned error: %v", err)
	}

	processor := NewDocumentProcessor(
		repository.NewGormDocumentProcessingRepository(db),
		baseStorage,
		providerService,
		indexing.NewDeterministicIndexer(),
		providerService,
		indexing.NewLLMEnricher(),
	)

	ctx, cancel := context.WithTimeout(context.Background(), 3*time.Minute)
	defer cancel()

	if err := processor.Process(ctx, domain.DocumentIndexRequestedEvent{
		DocumentID: document.ID,
		UserID:     user.ID,
	}); err != nil {
		t.Fatalf("Process returned error: %v", err)
	}

	var storedDocument models.Document
	if err := db.First(&storedDocument, document.ID).Error; err != nil {
		t.Fatalf("load processed document: %v", err)
	}
	if storedDocument.Status != domain.DocumentStatusIndexed {
		t.Fatalf("expected status %q, got %q", domain.DocumentStatusIndexed, storedDocument.Status)
	}
	if storedDocument.IndexedAt == nil {
		t.Fatal("expected indexed_at to be persisted")
	}

	var pages []models.DocumentPage
	if err := db.Where("document_id = ?", document.ID).Order("page_number ASC").Find(&pages).Error; err != nil {
		t.Fatalf("load pages: %v", err)
	}
	if len(pages) == 0 {
		t.Fatal("expected processed document pages to be persisted")
	}
	if strings.TrimSpace(pages[0].Summary) == "" {
		t.Fatal("expected page summary generated by LLM enrichment")
	}

	var metadataPairs []models.MetadataPair
	if err := db.Where("document_id = ?", document.ID).Find(&metadataPairs).Error; err != nil {
		t.Fatalf("load metadata pairs: %v", err)
	}

	metadata := map[string]string{}
	for _, pair := range metadataPairs {
		metadata[pair.Key] = pair.Value
	}

	if metadata["enrichment_status"] != "applied" {
		t.Fatalf("expected enrichment_status applied, got %q", metadata["enrichment_status"])
	}
	if strings.TrimSpace(metadata["document_summary"]) == "" {
		t.Fatal("expected document_summary metadata to be present")
	}
	if metadata["llm_provider_type"] != llmCfg.ProviderType {
		t.Fatalf("expected llm_provider_type %q, got %q", llmCfg.ProviderType, metadata["llm_provider_type"])
	}
	if requestCount, err := strconv.Atoi(metadata["llm_request_count"]); err != nil || requestCount <= 0 {
		t.Fatalf("expected positive llm_request_count, got %q err=%v", metadata["llm_request_count"], err)
	}
	if strings.TrimSpace(metadata["llm_model"]) == "" {
		t.Fatal("expected llm_model metadata to be present")
	}

	var outlineNodes []models.DocumentOutlineNode
	if err := db.Where("document_id = ?", document.ID).Order("sequence_order ASC").Find(&outlineNodes).Error; err != nil {
		t.Fatalf("load outline nodes: %v", err)
	}
	if len(outlineNodes) == 0 {
		t.Fatal("expected outline nodes to be persisted")
	}

	var chunks []models.DocumentChunk
	if err := db.Where("document_id = ?", document.ID).Order("sequence_order ASC").Find(&chunks).Error; err != nil {
		t.Fatalf("load chunks: %v", err)
	}
	if len(chunks) == 0 {
		t.Fatal("expected chunks to be persisted")
	}
}
